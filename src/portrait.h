#ifndef PORTRAIT_TYPES_H
#define PORTRAIT_TYPES_H
#include <stdint.h>
typedef enum {
    REACTION_IDLE, REACTION_HELLO, REACTION_START, REACTION_STOP,
    REACTION_MANUAL, REACTION_AUTO, REACTION_LEFT, REACTION_RIGHT,
    REACTION_UP, REACTION_DOWN, REACTION_DIAGONAL, REACTION_DARK,
    REACTION_BRIGHT, REACTION_ALIGNED, REACTION_LOW, REACTION_EMPTY,
    REACTION_RECOVERED, REACTION_LIMIT_LEFT, REACTION_LIMIT_RIGHT,
    REACTION_LIMIT_UP, REACTION_LIMIT_DOWN, REACTION_FAULT, REACTION_UNKNOWN,
    REACTION_COUNT
} reaction_t;
typedef enum { EYES_OPEN, EYES_CLOSED, EYES_HAPPY, EYES_TIRED } eyes_t;
typedef enum { ICON_NONE, ICON_HEART, ICON_LEFT, ICON_RIGHT, ICON_UP,
    ICON_DOWN, ICON_MOON, ICON_SUN, ICON_BATTERY, ICON_ALERT, ICON_STAR } icon_t;
typedef struct {
    int8_t dx, dy, lean, sway; /* signed 1/16 pixel; sway follows the shoulders */
    uint8_t eyes, reaction, icon, phase, eye_mix;
} portrait_frame_t;
#endif
